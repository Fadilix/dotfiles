#!/usr/bin/env bash
# Usage: MonitorMode.sh extend|duplicate|external|laptop [--side left|right|up|down] [--scale N] [--dry-run]
#   extend     - laptop + externals side by side
#   duplicate  - externals mirror the laptop panel
#   external   - laptop panel off, externals only
#   laptop     - externals off, laptop panel only
#   --side     - where extended screens sit relative to the laptop (default: right)
#   --scale    - laptop panel scale, e.g. 1, 1.2, 1.25, 1.5 (default: current)
#   --dry-run  - print the generated Lua instead of applying it
# Writes the layout to lua/monitor_mode.lua and reloads the native Lua config.
set -euo pipefail

mode="${1:-}"
[[ $# -gt 0 ]] && shift
side="right"
want_scale=""
dry_run=false
while [[ $# -gt 0 ]]; do
    case "$1" in
        --side) side="${2:-}"; shift 2 ;;
        --scale) want_scale="${2:-}"; shift 2 ;;
        --dry-run) dry_run=true; shift ;;
        *) echo "MonitorMode: unknown option $1" >&2; exit 2 ;;
    esac
done
case "$side" in left|right|up|down) ;; *) echo "MonitorMode: --side must be left, right, up or down" >&2; exit 2 ;; esac
if [[ -n "$want_scale" && ! "$want_scale" =~ ^[0-9]+(\.[0-9]+)?$ ]]; then
    echo "MonitorMode: --scale must be a number like 1.25" >&2; exit 2
fi
lua_config="$HOME/.config/hypr/lua/monitor_mode.lua"
backup_file=$(mktemp)
generated_file=$(mktemp)
trap 'rm -f "$backup_file" "$generated_file"' EXIT
had_config=false
if [[ -f "$lua_config" ]]; then cp "$lua_config" "$backup_file"; had_config=true; fi

mons=$(hyprctl monitors all -j)

internal=$(jq -r '[.[] | select(.name | startswith("eDP"))][0].name // empty' <<<"$mons")
scale=$(jq -r '[.[] | select(.name | startswith("eDP"))][0].scale // 1' <<<"$mons")
[[ -n "$want_scale" ]] && scale="$want_scale"
mapfile -t externals < <(jq -r '.[] | select(.name | startswith("eDP") | not) | .name' <<<"$mons")

if [[ -z "$internal" ]]; then
    echo "MonitorMode: no laptop panel (eDP-*) found" >&2
    exit 1
fi

enable=()   # config lines, applied first so mirror sources exist before mirrors
disable=()  # applied last, so windows move before a panel is switched off

case "$mode" in
    extend)
        enable+=("$internal,preferred,0x0,$scale")
        for e in "${externals[@]}"; do enable+=("$e,preferred,auto-$side,1"); done
        ;;
    duplicate)
        enable+=("$internal,preferred,0x0,$scale")
        for e in "${externals[@]}"; do enable+=("$e,preferred,auto,1,mirror,$internal"); done
        ;;
    external)
        for e in "${externals[@]}"; do enable+=("$e,preferred,auto,1"); done
        disable+=("$internal,disable")
        ;;
    laptop)
        enable+=("$internal,preferred,0x0,$scale")
        for e in "${externals[@]}"; do disable+=("$e,disable"); done
        ;;
    *)
        echo "usage: $0 extend|duplicate|external|laptop" >&2
        exit 2
        ;;
esac

if [[ ${#externals[@]} -eq 0 && "$mode" != "laptop" ]]; then
    echo "MonitorMode: no external monitor connected" >&2
    exit 1
fi

all=("${enable[@]}" "${disable[@]}")

lua_quote() {
    jq -Rn --arg value "$1" '$value'
}

{
    echo "-- Generated by UserScripts/MonitorMode.sh (mode=$mode side=$side scale=$scale); changes are overwritten when you pick a mode."
    for line in "${all[@]}"; do
        IFS=, read -r output monitor_mode position scale mirror_keyword mirror_output <<< "$line"
        output_lua=$(lua_quote "$output")
        if [[ "$monitor_mode" == "disable" ]]; then
            printf 'hl.monitor({ output = %s, disabled = true })\n' "$output_lua"
            continue
        fi
        extra=""
        [[ "$output" == eDP* ]] && extra=", bitdepth = 10"   # the laptop panel is a 10-bit display
        mode_lua=$(lua_quote "$monitor_mode")
        position_lua=$(lua_quote "$position")
        if [[ -n "$mirror_output" && "$mirror_keyword" == "mirror" ]]; then
            mirror_lua=$(lua_quote "$mirror_output")
            printf 'hl.monitor({ output = %s, mode = %s, position = %s, scale = %s, mirror = %s%s })\n' \
                "$output_lua" "$mode_lua" "$position_lua" "$scale" "$mirror_lua" "$extra"
        else
            printf 'hl.monitor({ output = %s, mode = %s, position = %s, scale = %s%s })\n' \
                "$output_lua" "$mode_lua" "$position_lua" "$scale" "$extra"
        fi
    done
} > "$generated_file"
if $dry_run; then cat "$generated_file"; exit 0; fi
mv "$generated_file" "$lua_config"

hyprctl reload >/dev/null || true
errors=$(hyprctl configerrors)
if [[ -n "$errors" ]]; then
    if $had_config; then cp "$backup_file" "$lua_config"; else rm -f "$lua_config"; fi
    hyprctl reload >/dev/null || true
    rm -f "$backup_file"
    echo "MonitorMode: failed to load the Lua monitor layout; restored the previous one" >&2
    exit 1
fi
rm -f "$backup_file"

command -v notify-send >/dev/null && notify-send "Monitors" "Layout: $mode" || true
